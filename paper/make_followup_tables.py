def write_table(filename, header, rows, columns, first_header=None):
    lines = ["% Generated by python3 -m paper.make_followup_tables.", rf"\begin{{tabular}}{{{columns}}}", r"\toprule"]
    if first_header:
        lines.extend(first_header)
    lines.extend([" & ".join(header) + r" \\", r"\midrule"])
    lines.extend(" & ".join(row) + r" \\" for row in rows)
    lines.extend([r"\bottomrule", r"\end{tabular}"])
    (PAPER / "generated" / filename).write_text("\n".join(lines) + "\n")


def write_csv(filename, header, rows):
    with (PAPER / "generated" / filename).open("w", newline="") as output:
        writer = csv.writer(output, lineterminator="\n")
        writer.writerow(header)
        writer.writerows(rows)


def load_summaries():
    for model, label, review_count in MODELS:
        path = SUMMARY / f"{model}.json"
        summary = json.loads(path.read_text())
        if any(summary["selector"][market]["tasks"] != 832 for market, _ in MARKETS):
            raise ValueError(f"Unexpected matched panel in {path}")
        if summary.get("new_disclosed_reviews") != review_count or summary.get("caps", {}).get("tasks") != 96:
            raise ValueError(f"Incomplete disclosed review or cap results in {path}")
        yield label, summary


def pct(value):
    return f"{100 * value:.1f}"


def model_breadth_tables():
    from scripts.model_breadth_report import MODELS as BREADTH_MODELS, SYNTHETIC_COUNTS

    source = BREADTH / "summary.json"
    report = json.loads(source.read_text())
    models = report["models"]
    if [entry["model"] for entry in models] != list(BREADTH_MODELS) or report["synthetic_tasks"] != SYNTHETIC_COUNTS:
        raise ValueError(f"The paper requires the entire frozen multi-model panel in {source}")

    figure_markets = ("decoy", "decoy_injection", "unconditioned")
    rows, public, optimality, failures, catalog_diagnostics, disclosure = [], [], [], [], [], []
    for index, entry in enumerate(models, start=1):
        label = entry["label"]
        note = entry["synthetic"]["decoy_injection"]["rates"]
        changes = {}
        for market in figure_markets:
            result = entry["synthetic"][market]
            counts, tasks = result["counts"], result["tasks"]
            changes[market] = (
                100 * (counts["disclosed_optimal"] - counts["opaque_optimal"]) / tasks,
                100 * (counts["opaque_failure"] - counts["disclosed_failure"]) / tasks,
            )
        gain = changes["decoy_injection"][0]
        disclosure.append([label, index, *(value for pair in changes.values() for value in pair)])
        rows.append([label, *(pct(note[key]) for key in ("one_optimal", "pool_optimal", "opaque_optimal", "disclosed_optimal")),
                     f"{gain:+.1f}" if gain else "0.0"])
        catalog = entry["catalogs"]["pooled"]
        leading = catalog["leading_json"]
        before, after = leading["opaque"], leading["verified"]
        if (catalog["tasks"], catalog["feasible"], after["unsafe"]) != (96, 67, 0):
            raise ValueError(f"Unexpected fixed-pair catalog panel for {label}")
        public.append([label, f"{before['unsafe']}/{before['approved']}", str(after["compliant"]),
                       str(catalog["verified"]["optimal"]), str(after["optimal"])])
        raw, valid_ids = catalog["opaque"], "known_initial_ids"
        lookups = [catalog["policies"][key] for key in ("two_drafts_two_sources", "selective_two_sources", "review_after_source")]
        catalog_diagnostics.append([label, f"{catalog[valid_ids]}/{catalog['unfenced'][valid_ids]}/{leading[valid_ids]}",
                                    f"{raw['unsafe']}/{raw['approved']}", str(catalog["verified"]["optimal"]),
                                    *(f"{arm['optimal']}/{arm['sources']}" for arm in lookups)])
        rates = [entry["synthetic"][name]["rates"] for name in SYNTHETIC_COUNTS]
        optimality.append([label, *(pct(row[key]) for row in rates for key in ("opaque_optimal", "disclosed_optimal"))])
        failures.append([label, *(pct(row[key]) for row in rates for key in ("opaque_failure", "disclosed_failure"))])

    write_table("table_breadth_selection.tex", ["Checkpoint", "One", "In pool", "Opaque", "Disclosed", "Gain"], rows, "lrrrrr")
    write_csv("breadth_disclosure.csv",
              ("model", "row", *(f"{market}_{metric}" for market in figure_markets for metric in ("optimal", "failure"))),
              disclosure)
    write_table("table_breadth_catalogs.tex", ["Checkpoint", "Over budget", "Compliant", "Bare JSON", "Fences"], public, "lrrrr",
                [r" & & & \multicolumn{2}{c}{Optima} \\", r"\cmidrule(lr){4-5}"])
    heading = [r" & \multicolumn{2}{c}{Benign} & \multicolumn{2}{c}{Decoy} & \multicolumn{2}{c}{Decoy + note} & \multicolumn{2}{c}{Unconditioned} \\",
               r"\cmidrule(lr){2-3}\cmidrule(lr){4-5}\cmidrule(lr){6-7}\cmidrule(lr){8-9}"]
    header = ["Checkpoint", *(["Opaque", "Discl."] * 4)]
    write_table("table_breadth_optimality.tex", header, optimality, "lrrrrrrrr", heading)
    write_table("table_breadth_failure.tex", header, failures, "lrrrrrrrr", heading)
    heading = [r" & & \multicolumn{2}{c}{Strict JSON} & \multicolumn{3}{c}{Optima / lookups with strict JSON} \\",
               r"\cmidrule(lr){3-4}\cmidrule(lr){5-7}"]
    write_table("table_breadth_catalog_diagnostics.tex",
                ["Checkpoint", "Known IDs", "Over / app.", "Optima", "Two nominations", "Selective lookup", "Evidence review"],
                catalog_diagnostics, "lrrrrrr", heading)


def fixed_scenario(summary, regime, penalty):
    return next(row for row in summary["scenarios"][regime]["sensitivity"]
                if (row["penalty"], row["dollars_per_million"], row["dollars_per_second"]) == (penalty, 10, 0))


def paired_estimate(est):
    return f"{est['delta']:.2f} [{est['low']:.2f}, {est['high']:.2f}]"


def savings(row):
    return paired_estimate(row["paired_savings"]["budget_only"])


