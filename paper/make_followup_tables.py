    refit = json.loads((CATALOG / "effort-refit.json").read_text())
    rows = []
    for model, label, _ in MODELS:
        for case in refit[model]:
            if (case["calibration_seeds"], case["test_seeds"], case["replicates"]) != (208, 832, 2000):
                raise ValueError(f"Incomplete calibration refit for {model}")
            overhead = case["referral_cost"]
            if overhead is None:
                penalty, referral = f"{case['penalty']:.0%}".replace("%", r"\%"), "--"
            else:
                penalty, referral = "--", r"\$" + f"{overhead:g}"
            low, high = case["interval"]
            rows.append([label, penalty, referral, paired_estimate({"delta": case["difference"], "low": low, "high": high})])
    write_table("table_refit_effort.tex", ["Model", "Penalty", "Referral", "Savings"], rows, "lrrr")

    guard = json.loads((CATALOG / "quote-guard.json").read_text())["models"]
    reports = [guard[model] for model in ("qwen3-4b-q4", "qwen3-8b-q4")]
    if any(report["rows"] != 312 for report in reports):
        raise ValueError("The price guard requires all archived label estimates")
    rows = []
    for arm, label in (("page_only", "Full page"), ("exact_match", "Exact price match"), ("table_only", "Matched table"),
                       ("both_full_page", "Both prices fit"), ("always_scoped", "Always read panel"),
                       ("selective_scoped", "Selective panel read")):
        outcomes = [report["pooled"][arm] for report in reports]
        rows.append([label, *(value for row in outcomes for value in (f"{row['over_either']}/{row['approved']}", str(row["scoped_lookups"])))])
    write_table("table_quote_guard.tex", ["Policy", "Over / all", "Lookups", "Over / all", "Lookups"], rows, "lrrrr",
                [r" & \multicolumn{2}{c}{Qwen3-4B} & \multicolumn{2}{c}{Qwen3-8B} \\", r"\cmidrule(lr){2-3}\cmidrule(lr){4-5}"])

    catalog = json.loads((CATALOG / "catalog-model.json").read_text())
    panels = list(catalog["model"].values())
    if len(panels) != 8 or any(row["cases"] != 12 for row in panels):
        raise ValueError("The catalog table requires the complete 96-task panel")
    rows = []
    for arm, label in (("all_sources", "All sources"), ("headline_one", "One lookup"),
                       ("headline_two", "Fixed order, up to two"), ("headline_with_stopping", "Headline with stopping"),
                       ("one_draft", "Draft then look up"), ("two_drafts_two_sources", "Two drafts, two lookups"),
                       ("selective_two_sources", "Draft with stopping"), ("review_after_source", "Look up then review")):
        outcomes = [row["policies"][arm] for row in panels]
        if any(row["unsafe"] for row in outcomes):
            raise ValueError(f"Inconsistent verified replay for {arm}")
        metrics = (sum(row[key] for row in outcomes) for key in ("optimal", "compliant", "sources", "tokens"))
        optimal, compliant, sources, tokens = metrics
        rows.append([label, str(optimal), str(compliant), str(sources), f"{tokens / 1000:.1f}"])
    write_table("table_catalog_gate.tex", ["Policy", "Optima", "Compliant", "Lookups", "Tokens"], rows, "lrrrr")

    rows, short_effort = [], []
    short_models = (("qwen3-8b-q4", "qwen3-8b-q4", "Qwen3-8B"),
                    ("gemma-3-4b-q4", "gemma-3-4b-q4", "Gemma 3 4B"),
                    ("mistral-7b-v03-q4", "mistral-7b-v03-q4", "Mistral 7B"),
                    ("mistral-512", "mistral-7b-v03-q4", "Mistral (512)"))
    penalties = (20, 50)
    for index, (result, model, label) in enumerate(short_models, start=1):
        path = REVIEW_LOOP / f"short-effort-{result}.json"
        report = json.loads(path.read_text())
        if (report["checkpoint"]["model"], report["calibration_tasks"], report["test_tasks"]) != (model, 108, 432):
            raise ValueError(f"Unexpected short-effort panel in {path}")
        if result == "mistral-512" and report.get("review_cap") != 512:
            raise ValueError(f"Expected the 512-token review cap in {path}")
        figure_row = [label, index]
        for penalty, opaque, disclosed in zip(penalties, report["regimes"]["opaque"], report["regimes"]["disclosed"], strict=True):
            cells = []
            for scenario in (opaque, disclosed):
                if (scenario["penalty"], scenario["dollars_per_million"], scenario["dollars_per_second"]) != (penalty / 100, 10, 0):
                    raise ValueError(f"Unexpected short-effort pricing in {path}")
                estimate = scenario["refitted"]
                low, high = estimate["interval"]
                point = estimate["point"]
                cells.append(paired_estimate({"delta": point, "low": low, "high": high}))
                figure_row.extend((point, low, high))
            rows.append([label, rf"{penalty}\%", *cells])
        if result != "mistral-512":
            short_effort.append(figure_row)
    write_table("table_short_effort_transfer.tex", ["Model", "Penalty", "Opaque", "Disclosed"], rows, "lrrr")
    full_effort = RESULTS / "short_effort_breadth_2026-11-26" / "summary.json"
    if full_effort.is_file():
        from scripts.model_breadth_report import MODELS as BREADTH_MODELS

        matched = json.loads(full_effort.read_text())["models"]
        if [model["model"] for model in matched] != list(BREADTH_MODELS):
            raise ValueError(f"The short-action panels need all 14 checkpoint replays in {full_effort}")
        short_effort, all_rows = [], []
        for index, model in enumerate(matched, start=1):
            estimates = [model["regimes"][check][scenario]["refitted"]
                         for scenario in range(len(penalties)) for check in ("opaque", "disclosed")]
            values = [(row["point"], *row["interval"]) for row in estimates]
