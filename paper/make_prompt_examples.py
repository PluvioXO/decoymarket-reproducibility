"""Render the paper's worked example with the benchmark's prompt functions."""
import json
from pathlib import Path

from decoymarket.benchmark import canonical_decision, evaluate, task_from_json
from decoymarket.prompts import DECISION_INSTRUCTIONS, drafter_prompt, reviewer_prompt


PAPER_DIR = Path(__file__).resolve().parent


def listings():
    task = task_from_json(json.loads((PAPER_DIR / "decoy-3.json").read_text()))
    offer = next(offer for offer in task.offers if offer.seller in task.decoy_sellers)
    decision = canonical_decision(offer, task.mandate)
    system, user = drafter_prompt(task)
    context = user["content"].removesuffix("\n\n" + DECISION_INSTRUCTIONS)
    no_report = reviewer_prompt(task, decision)[1]["content"].removeprefix(context)
    proposal, instructions = no_report.lstrip("\n").split("\n\n", 1)

    yield "Shared system message", system["content"]
    yield "Shared task text", context
    yield "Drafter instructions", DECISION_INSTRUCTIONS
    yield "Selected decision shown to the reviewer", proposal
    for regime in ("opaque", "disclosed"):
        check = evaluate(task, decision, regime)
        report = dict(seller=decision.seller, passes=check["passes"],
                      failed=check["failed"], visible=check["visible"])
        text = reviewer_prompt(task, decision, "report", report)[1]["content"]
        text = text.removeprefix(context + "\n\n" + proposal + "\n\n")
        yield f"{regime.capitalize()} check report", text.removesuffix("\n\n" + instructions)
    yield "Reviewer instructions", instructions


if __name__ == "__main__":
    target = PAPER_DIR / "generated" / "prompts.tex"
    parts = ["% Generated by python3 -m paper.make_prompt_examples.\n"]
    for title, text in listings():
        block = (
            f"\\textbf{{{title}}}\\par\\nopagebreak[4]\n"
            f"\\begin{{lstlisting}}\n{text}\n\\end{{lstlisting}}\n"
        )
        if title != "Shared task text":
            block = f"\\begin{{minipage}}{{\\linewidth}}\n{block}\\end{{minipage}}\n"
        parts.append("\\par\\smallskip\\noindent" + block)
    target.write_text("\n".join(parts))
