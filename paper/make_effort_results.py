"""Build the workshop paper's descriptive results from the verified live runs."""
from __future__ import annotations

import argparse
import hashlib
import json
import os
from pathlib import Path
from statistics import mean

from decoymarket.benchmark import Decision, classify_failure, selection_key, task_from_json
from decoymarket.estimators import selection_weights
from paper.make_followup_tables import main as write_followup_tables
from paper.make_followup_tables import write_csv

PAPER = Path(__file__).resolve().parent
RESULTS = Path(os.environ.get("DECOYMARKET_RESULTS", PAPER.parent / "results"))
MODELS = (("qwen3-8b", "Qwen"), ("llama31-8b", "Llama"))
MARKETS = (("benign", "Benign"), ("decoy", "Decoy"), ("decoy_injection", "Decoy + note"))


def load_live(model, market, expected_sha256=None):
    path = RESULTS / model / f"{market}_test.json"
    raw = path.read_bytes()
    episode = json.loads(raw)
    if (
        (expected_sha256 is not None and hashlib.sha256(raw).hexdigest() != expected_sha256)
        or episode["backend"] != "live"
        or episode["is_mock"]
        or episode["stopped_early"]
        or episode["model_name"] != model
        or episode["market"] != market
        or [row["task"]["seed"] for row in episode["tasks"]] != list(range(10001, 10201))
        or any(len(row["drafts"]) != 16 for row in episode["tasks"])
    ):
        raise ValueError(f"Expected the complete live test split at {path}")
    return episode["tasks"]


def curves(rows, regime, ks):
    optimal = {k: [] for k in ks}
    decoy = {k: [] for k in ks}
    for row in rows:
        task = task_from_json(row["task"])
        drafts = [Decision.from_json(item["decision"]) for item in row["drafts"]]
        scores = [classify_failure(task, draft)["success"] for draft in drafts]
        planted = [draft.seller in task.decoy_sellers for draft in drafts]
        order = sorted(range(16), key=lambda i: selection_key(task, drafts[i], regime) + (i,))
        for k in ks:
            weights = selection_weights(16, order, k)
            optimal[k].append(sum(weight * score for weight, score in zip(weights, scores)))
            decoy[k].append(sum(weight * hit for weight, hit in zip(weights, planted)))
    return {k: mean(v) for k, v in optimal.items()}, {k: mean(v) for k, v in decoy.items()}


def write_tex(name, lines):
    (PAPER / "generated" / name).write_text(
        "% Generated by python3 -m paper.make_effort_results.\n" + "\n".join(lines) + "\n"
    )


def selection_row(label, market_label, opaque, disclosed):
    rates = [opaque[k] for k in (1, 4, 16)] + [disclosed[16]]
    return " & ".join([label, market_label, *(f"{100 * p:.1f}" for p in rates)]) + r" \\"


def write_matched_evidence():
    study = json.loads((RESULTS / "distributed_effort" / "summary.json").read_text())
    plan = study["plan"]
    if (
        plan["model"] != "qwen3-8b-q4"
        or plan["short_drafts"] != 8
        or plan["think_caps"] != [1024, 2048]
        or study["calibration_tasks"] != 1686
        or study["test_tasks"] != 6744
        or set(study["worker_coverage"]) != set(plan["workers"])
        or any(worker["completed_blocks"] != worker["planned_blocks"] or worker["exit_code"] != 0
               for worker in study["worker_coverage"].values())
    ):
        raise ValueError("The matched figures and table require the completed study")
    scenarios = study["scenarios_by_violation_penalty"]
    full_selector = json.loads((RESULTS / "effort_followup_2026-11-25" / "full-8b-selector.json").read_text())
    table_rows, optimality_rows = [], []
    for index, (market, label) in enumerate(MARKETS, 1):
        frontier = study["descriptive"][market]["frontiers"]
        opaque, disclosed = frontier["opaque"], frontier["disclosed"]
        rates = [
            100 * item["optimal_rate"]
            for item in (opaque["short_1"], opaque["short_8"], disclosed["short_8"],
                         opaque["think_1024"], opaque["think_2048"])
        ]
        table_rows.append(" & ".join([label, *(f"{rate:.1f}" for rate in rates)]) + r" \\")
        ranked = scenarios["0.2"]["by_market"][market]["policies"]["think_2048"]["optimal_rate"]
        if full_selector[market]["tasks"] != 2248:
            raise ValueError(f"Unexpected full 8B panel for {market}")
        disclosed = full_selector[market]["long_added_disclosed"]
        optimality_rows.append([index, rates[1], rates[2], rates[4], 100 * ranked, 100 * disclosed])
    write_tex("table_distributed_effort.tex", [
        r"\begin{tabular}{lrrrrr}",
        r"\toprule",
        r" & \multicolumn{2}{c}{Short, opaque} & Short, disclosed & \multicolumn{2}{c}{Thinking} \\",
        r"\cmidrule(lr){2-3}\cmidrule(lr){4-4}\cmidrule(l){5-6}",
        r"Market & 1 & 8 & 8 & 1,024 & 2,048 \\",
        r"\midrule",
        *table_rows,
        r"\bottomrule",
        r"\end{tabular}",
    ])
    write_csv(
        "matched_optimality.csv",
        ("market", "short_opaque", "short_disclosed", "thinking_alone", "thinking_ranked", "thinking_ranked_disclosed"),
        optimality_rows,
    )
    auto_rows = []
    for index, penalty in enumerate(("0.1", "0.2", "0.5"), 1):
        policies = scenarios[penalty]["overall"]["policies"]
        costs = [policies[name]["loss_plus_inference"] for name in ("best_fixed", "budget_only", "auto")]
        shares = policies["auto"]["action_shares"]
        if any(shares[action] for action in ("stop", "draft", "think_1024")):
            raise ValueError(f"Unexpected Auto action at penalty {penalty}")
        auto_rows.append([index, *costs, 100 * shares["think_2048"], 100 * shares["review"]])
    write_csv(
        "matched_auto.csv",
        ("scenario", "fixed_cost", "budget_cost", "auto_cost", "thinking_share", "review_share"),
        auto_rows,
    )
    write_followup_tables()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--matched-only", action="store_true")
    if parser.parse_args().matched_only:
        write_matched_evidence()
        return
    auto = json.loads((RESULTS / "auto_effort.json").read_text())
    if (auto["regime"], auto["initial_drafts"], auto["violation_penalty_fraction_of_optimal_price"],
        auto["dollars_per_million_tokens"]) != ("opaque", 2, 0.20, 10):
        raise ValueError("The manuscript's tables use the default Auto replay scenario")
    selection_rows, attack_curves, auto_rows = [], {}, []
    for model, label in MODELS:
        for market, market_label in MARKETS:
            expected = auto["input_sha256"][f"results/{model}/{market}_test.json"]
            rows = load_live(model, market, expected)
            ks = range(1, 17) if market == "decoy" else (1, 4, 16)
            opaque, planted = curves(rows, "opaque", ks)
            disclosed, _ = curves(rows, "disclosed", (16,))
            selection_rows.append(selection_row(label, market_label, opaque, disclosed))
            if market == "decoy":
                attack_curves[label] = planted
        full_stakes = next(item for item in auto["models"][model]["scenarios"] if item["stake_scale"] == 1)
        policies = full_stakes["policies"]
        costs = [policies[name]["loss_plus_inference"] for name in ("agree2", "best_fixed", "price_only", "auto")]
        auto_rows.append(" & ".join([label, *(rf"\${cost:.2f}" for cost in costs)]) + r" \\")

    phi = load_live("phi-4-mini", "benign")
    phi_opaque, _ = curves(phi, "opaque", (1, 4, 16))
    phi_disclosed, _ = curves(phi, "disclosed", (16,))

    write_tex("table_effort_selection.tex", [
        r"\begin{tabular}{llrrrr}",
        r"\toprule",
        r" & & \multicolumn{3}{c}{Opaque} & Disclosed \\",
        r"\cmidrule(lr){3-5}\cmidrule(l){6-6}",
        r"Model & Market & $k=1$ & $k=4$ & $k=16$ & $k=16$ \\",
        r"\midrule",
        *selection_rows[:3],
        r"\addlinespace",
        *selection_rows[3:],
        r"\addlinespace",
        selection_row("Phi", "Benign", phi_opaque, phi_disclosed),
        r"\bottomrule",
        r"\end{tabular}",
    ])
    write_tex("table_auto_effort.tex", [
        r"\begin{tabular}{lrrrr}",
        r"\toprule",
        r"Model & AGREE2 & Fixed & Budget & Auto \\",
        r"\midrule",
        *auto_rows,
        r"\bottomrule",
        r"\end{tabular}",
    ])
    write_matched_evidence()
    styles = {"Qwen": "blue!70!black,thick,mark=square*", "Llama": "orange!80!black,thick,dashed,mark=*"}
    plot = [
        r"\documentclass{standalone}",
        r"\usepackage{newtxtext}",
        r"\usepackage{pgfplots}",
        r"\pgfplotsset{compat=1.17}",
        r"\begin{document}",
        r"\begin{tikzpicture}",
        r"\begin{axis}[width=3.3125in,height=4.5cm,",
        r"  xmin=1,xmax=16,ymin=0,ymax=65,xtick={1,4,8,12,16},ytick={0,20,40,60},",
        r"  xlabel={Number of drafts $k$},ylabel={Planted seller selected (\%)},",
        r"  legend pos=north west,legend style={font=\normalsize,draw=none,fill=none},",
        r"  tick label style={font=\normalsize},label style={font=\normalsize}]",
    ]
    for label, curve in attack_curves.items():
        coordinates = " ".join(f"({k},{100 * rate:.3f})" for k, rate in curve.items())
        plot.append(rf"\addplot[{styles[label]},mark size=1.2pt,mark repeat=3] coordinates {{{coordinates}}};")
        plot.append(rf"\addlegendentry{{{label}}}")
    write_tex("fig_decoy_selection.tex", [*plot, r"\end{axis}", r"\end{tikzpicture}", r"\end{document}"])


if __name__ == "__main__":
    main()
