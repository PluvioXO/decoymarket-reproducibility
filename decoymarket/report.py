"""Turn episode logs into the paper's generated LaTeX: result macros, tables, and the figure.

Reads episodes named ``{market}_{split}.json`` (split in cal, test) from a results directory and
writes into paper/generated/. If any episode used the mock backend, the status is set to ``mock``
so the paper prints a MOCK DATA banner and no number can be mistaken for a model measurement.
"""
from __future__ import annotations

import json
from pathlib import Path

from . import analysis as an
from .benchmark import _offer_by_seller, generate_task, optimum
from .prompts import render_offers

MARKET_LABEL = {"benign": "Benign", "decoy": "Decoy", "decoy_injection": "Decoy+inj."}


def pct(x, d=1):
    return "--" if x is None else f"{100 * x:.{d}f}"


def num(x, d=3):
    return "--" if x is None else f"{x:.{d}f}"


def _single_draft_shares(test_tds, regime):
    from .analysis import classify
    counts = {"S": 0, "A": 0, "B": 0, "N": 0}
    n = 0
    for td in test_tds:
        for d in td.drafts:
            counts[an.classify(td.task, d, regime)] += 1
            n += 1
    return {k: v / n for k, v in counts.items()} if n else counts


def build(results_dir: str, generated_dir: str):
    rd = Path(results_dir)
    gd = Path(generated_dir)
    gd.mkdir(parents=True, exist_ok=True)

    markets = [m for m in ("benign", "decoy", "decoy_injection")
               if (rd / f"{m}_cal.json").exists() and (rd / f"{m}_test.json").exists()]
    if not markets:
        raise SystemExit(f"no {{market}}_cal.json / {{market}}_test.json pairs in {rd}")

    analyses = {}
    is_mock = False
    model_name = "the open-weight model"
    shares = {}
    for m in markets:
        cal = str(rd / f"{m}_cal.json")
        test = str(rd / f"{m}_test.json")
        res = an.run_analysis(cal, test, regime="opaque", report_info="report")
        analyses[m] = res
        is_mock = is_mock or res["is_mock"]
        meta, test_tds = an.load_episode(test)
        model_name = meta["model_name"]
        shares[m] = _single_draft_shares(test_tds, "opaque")

    _write_results_tex(gd, analyses, shares, model_name, is_mock)
    _write_table_rates(gd, analyses, shares)
    _write_table_hypotheses(gd, analyses)
    _write_table_prediction(gd, analyses)
    _write_fig_frontier(gd, analyses)
    _write_example(gd)
    return analyses


def _defres(key, value):
    return "\\defres{%s}{%s}\n" % (key, value)


def _write_results_tex(gd, analyses, shares, model_name, is_mock):
    lines = ["% Generated by `python -m decoymarket report`. Do not edit by hand.\n"]
    lines.append(_defres("status", "mock" if is_mock else "live"))
    lines.append(_defres("main.model", model_name.replace("_", "\\_")))
    if "decoy" in analyses:
        d = analyses["decoy"]
        lines.append(_defres("main.decoy.opaque.p1", pct(d["p1"]) + "\\%"))
        lines.append(_defres("main.decoy.opaque.a", num(shares["decoy"]["A"], 3)))
        lines.append(_defres("main.decoy.opaque.pbest", pct(d["peak"]) + "\\%"))
        lines.append(_defres("main.decoy.opaque.kbest", str(d["peak_k"])))
        lines.append(_defres("main.decoy.opaque.p16", pct(d["p16"]) + "\\%"))
        lines.append(_defres("main.decoy.disclosed.p16", pct(d["p16_disclosed"]) + "\\%"))
        f = d["forecast"]
        kb = d["peak_k"]
        draftword = "draft" if kb == 1 else "drafts"
        summary = (
            "In decoy markets, success peaked at %s\\%% with %d %s and fell to %s\\%% at 16; "
            "disclosure restored it to %s\\%%, and the rates forecaster cut 16-draft regret from "
            "%s to %s versus a scale-up rule."
            % (pct(d["peak"]), kb, draftword, pct(d["p16"]), pct(d["p16_disclosed"]),
               num(f["scaleup_regret16"]), num(f["rates_regret16"]))
        )
        lines.append(_defres("abstract.summary", summary))
        lines.append(_defres("intro.status", "measured results on DecoyMarket."))
    if "benign" in analyses:
        b = analyses["benign"]
        lines.append(_defres("main.benign.opaque.p1", pct(b["p1"]) + "\\%"))
    (gd / "results.tex").write_text("".join(lines))


def _ci(lo, hi):
    return "--" if lo is None else f"[{lo:.2f},{hi:.2f}]"


def _tabular(colspec, header, body, tabcolsep=4):
    return (
        "{\\footnotesize\\setlength{\\tabcolsep}{%dpt}\n" % tabcolsep
        + "\\begin{tabular}{%s}\n\\toprule\n" % colspec
        + header + "\n\\midrule\n" + body + "\n\\bottomrule\n\\end{tabular}}\n"
    )


def _write_table_rates(gd, analyses, shares):
    rows = []
    for m, res in analyses.items():
        sh = shares[m]
        f = res["forecast"]["rates_params"]
        rows.append(" & ".join([
            MARKET_LABEL[m], num(sh["S"], 2), num(sh["A"], 2), num(sh["B"], 2), num(sh["N"], 2),
            num(f["beta"], 2), num(f["phiA"], 2), num(f["phiB"], 2), num(f["phiN"], 2),
        ]) + " \\\\")
    header = "Market & $s$ & $a$ & $b$ & $n$ & $\\beta$ & $\\phi_A$ & $\\phi_B$ & $\\phi_N$ \\\\"
    (gd / "table_rates.tex").write_text(_tabular("lcccccccc", header, "\n".join(rows)))


def _verdict(delta, lo, hi, direction=">"):
    if delta is None or lo is None:
        return "--"
    if direction == ">":
        return "\\checkmark" if lo > 0 else "n.s."
    return "\\checkmark" if hi < 0 else "n.s."


def _write_table_hypotheses(gd, analyses):
    rows = []

    def add(name, market, delta, lo, hi, direction=">"):
        rows.append(" & ".join([
            name, MARKET_LABEL[market], num(delta, 3), _ci(lo, hi),
            _verdict(delta, lo, hi, direction),
        ]) + " \\\\")

    if "benign" in analyses:
        b = analyses["benign"]
        add("H1 rise", "benign", b["H1_delta"], b["H1_lo"], b["H1_hi"], ">")
    if "decoy" in analyses:
        d = analyses["decoy"]
        add("H1 reverse", "decoy", d["H1_delta"], d["H1_lo"], d["H1_hi"], ">")
        add("H2 disclose", "decoy", d["H2_delta"], d["H2_lo"], d["H2_hi"], ">")
        add("H3 review", "decoy", d["H3_delta"], d["H3_lo"], d["H3_hi"], ">")
        add("H5 AGREE2", "decoy", d["H5_delta"], d.get("H5_lo"), d.get("H5_hi"), ">")
        h6 = d["H6_delta"]
        rows.append(" & ".join([
            "H6 report", "decoy", num(h6, 3),
            f"{num(d['H6_repair_none'],2)}/{num(d['H6_repair_report'],2)}", "expl.",
        ]) + " \\\\")
    header = "Hypothesis & Market & $\\Delta$ & 95\\% CI & Verdict \\\\"
    (gd / "table_hypotheses.tex").write_text(_tabular("llccc", header, "\n".join(rows)))


def _write_table_prediction(gd, analyses):
    rows = []
    for m, res in analyses.items():
        f = res["forecast"]
        rows.append(" & ".join([
            MARKET_LABEL[m], num(f["rates_mae"], 3), num(f["logit_mae"], 3),
            num(f["rates_regret16"], 3), num(f["logit_regret16"], 3), num(f["scaleup_regret16"], 3),
        ]) + " \\\\")
    header = (
        " & \\multicolumn{2}{c}{Menu MAE} & \\multicolumn{3}{c}{Regret at 16 (pts)} \\\\\n"
        "\\cmidrule(lr){2-3}\\cmidrule(lr){4-6}\n"
        "Market & Rates & Logit & Rates & Logit & Scale-up \\\\"
    )
    (gd / "table_prediction.tex").write_text(_tabular("lccccc", header, "\n".join(rows)))


def _coords(xs, ys):
    return " ".join(f"({x:.3f},{y:.4f})" for x, y in zip(xs, ys))


def _write_fig_frontier(gd, analyses):
    if "decoy" not in analyses:
        (gd / "fig_frontier.tex").write_text("% no decoy market available\n")
        return
    d = analyses["decoy"]
    fr = d["frontier"]
    frd = d["frontier_disclosed"]
    ks = fr["k"]
    nr = _coords([fr["cost0"][k] for k in ks], [fr["no_review"][k] for k in ks])
    rv = _coords([fr["cost1"][k] for k in ks], [fr["review"][k] for k in ks])
    dc = _coords([frd["cost0"][k] for k in ks], [frd["no_review"][k] for k in ks])
    a2x, a2y = fr["agree2"][1], fr["agree2"][0]
    tex = f"""\\begin{{tikzpicture}}
\\begin{{axis}}[width=\\columnwidth,height=5cm,xmin=0,ymin=0,ymax=1.02,
  xlabel={{mean token cost (draft-equivalents)}},ylabel={{selected-decision success}},
  legend style={{font=\\scriptsize,at={{(0.98,0.02)}},anchor=south east,draw=none,
  fill=white,fill opacity=0.85}},tick label style={{font=\\scriptsize}},label style={{font=\\footnotesize}}]
\\addplot[thick,red,mark=*,mark size=1pt] coordinates {{{nr}}};
\\addlegendentry{{opaque, no review}}
\\addplot[thick,blue,mark=square*,mark size=1pt] coordinates {{{rv}}};
\\addlegendentry{{opaque, one review}}
\\addplot[thick,black,densely dotted,mark=triangle*,mark size=1pt] coordinates {{{dc}}};
\\addlegendentry{{disclosed, no review}}
\\addplot[only marks,mark=diamond*,mark size=2.5pt,green!50!black] coordinates {{({a2x:.3f},{a2y:.4f})}};
\\addlegendentry{{AGREE2}}
\\end{{axis}}
\\end{{tikzpicture}}
"""
    (gd / "fig_frontier.tex").write_text(tex)


def _write_example(gd):
    t = generate_task(3, "decoy")
    opt = optimum(t)
    m = t.mandate
    body = [
        f"MANDATE: buy {m.quantity} x {m.category} >= {m.spec_threshold}{m.spec_unit}, "
        f"deliver <= {m.deadline_days}d, all-in budget ${m.budget}, no subscription.",
        f"  data allowed: {', '.join(m.allowed_fields)}",
        "OFFERS (abridged):",
    ]
    for o in t.offers:
        fine = []
        if o.service_pct:
            fine.append(f"{o.service_pct}% service fee")
        if o.handling_flat:
            fine.append(f"${o.handling_flat} handling")
        if o.subscription_required:
            fine.append("subscription required")
        tag = "  <-- DECOY" if o.seller in t.decoy_sellers else ""
        body.append(
            f"  {o.seller}: {o.spec}{m.spec_unit}, ${o.unit_price}/unit, "
            f"visible ${o.visible_total(m.quantity)}, fine print: "
            f"{'; '.join(fine) if fine else 'none'}{tag}")
    body.append(f"OPTIMUM: {opt['seller']} at ${opt['allin']} all-in.")
    text = "\n".join(body)
    (gd / "example_task.tex").write_text(
        "\\begin{lstlisting}\n" + text + "\n\\end{lstlisting}\n")
